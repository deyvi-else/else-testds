// Generates a React component and a Code Connect template for every icon SVG.
//
//   src/icons/svg/20px-mini-golf.svg  (exported from Figma, the single source)
//   src/icons/figma.json              (Figma name and node ID for each SVG)
//   -> src/icons/generated/MiniGolfIcon20.tsx
//   -> src/icons/generated/MiniGolfIcon20.figma.ts
//   -> src/icons/generated/index.ts    (exports every component)
//   -> src/icons/generated/catalog.ts  (icon list for Storybook)
//
// Run with `npm run icons`. Each SVG is cleaned on the way (see clean-svg.mjs). If any icon
// doesn't fit the pattern, the script lists every problem and writes nothing.

import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { cleanSvg } from './clean-svg.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
const svgDir = join(root, 'src/icons/svg');
const outDir = join(root, 'src/icons/generated');
const figma = JSON.parse(readFileSync(join(root, 'src/icons/figma.json'), 'utf8'));

const HEADER = '// Generated by scripts/icons/build-icons.mjs from src/icons/svg/. Do not hand-edit, run `npm run icons`';

/** "20px / Mini-golf" -> { size: "20px", component: "MiniGolfIcon20" } */
export function iconNames(figmaName) {
  const match = /^(\d+)px \/ (.+)$/.exec(figmaName);
  if (!match) return null;
  const [, px, name] = match;
  const pascal = name
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1).toLowerCase())
    .join('');
  return { size: `${px}px`, px: Number(px), component: `${pascal}Icon${px}` };
}

/** "20px / Mini-golf" -> "20px-mini-golf.svg" */
const expectedFile = (figmaName) =>
  figmaName.replace(' / ', '-').toLowerCase().replace(/[^a-z0-9]+/g, '-') + '.svg';

const camel = (name) =>
  name === 'xmlns' || name.startsWith('aria-') || name.startsWith('data-')
    ? name
    : name.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());

function toJsx(element, indent, isRoot) {
  const pad = '  '.repeat(indent);
  const attributes = element.attributes.map(({ name, value }) => ` ${camel(name)}="${value}"`).join('');
  const extra = isRoot ? ' {...iconA11yProps(label)}' : '';
  if (!element.children.length) return `${pad}<${element.name}${attributes}${extra} />`;
  const children = element.children.map((child) => toJsx(child, indent + 1, false)).join('\n');
  return `${pad}<${element.name}${attributes}${extra}>\n${children}\n${pad}</${element.name}>`;
}

function build() {
  const files = readdirSync(svgDir).filter((file) => file.endsWith('.svg')).sort();
  const problems = [];
  const report = [];
  const icons = [];

  for (const file of files) {
    const entry = figma.icons[file];
    if (!entry) {
      problems.push(`${file}: not in src/icons/figma.json`);
      continue;
    }
    const names = iconNames(entry.figmaName);
    if (!names) {
      problems.push(`${file}: Figma name "${entry.figmaName}" doesn't start with a size like "20px / "`);
      continue;
    }
    if (expectedFile(entry.figmaName) !== file) {
      problems.push(`${file}: Figma name "${entry.figmaName}" would be saved as ${expectedFile(entry.figmaName)}`);
    }
    let result;
    try {
      result = cleanSvg(readFileSync(join(svgDir, file), 'utf8'), names.px);
    } catch (error) {
      problems.push(`${file}: ${error.message}`);
      continue;
    }
    problems.push(...result.problems.map((p) => `${file}: ${p}`));
    report.push({ file, ...result.changes, warnings: result.warnings });
    icons.push({ file, ...entry, ...names, svg: result.svg });
  }
  for (const file of Object.keys(figma.icons)) {
    if (!files.includes(file)) problems.push(`${file}: in src/icons/figma.json but not in src/icons/svg/`);
  }
  const seen = new Map();
  for (const icon of icons) {
    if (seen.has(icon.component)) problems.push(`${icon.file} and ${seen.get(icon.component)} both become ${icon.component}`);
    seen.set(icon.component, icon.file);
  }

  if (problems.length) {
    console.error(`Icons not generated. ${problems.length} problem(s):\n${problems.map((p) => `  - ${p}`).join('\n')}`);
    process.exit(1);
  }

  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });

  for (const icon of icons) {
    const source = relative(root, join(outDir, `${icon.component}.tsx`));
    writeFileSync(
      join(outDir, `${icon.component}.tsx`),
      `${HEADER}
import { iconA11yProps, type IconProps } from '../IconProps';

/** Figma: ${icon.figmaName} */
export function ${icon.component}({ label }: IconProps) {
  return (
${toJsx(icon.svg, 2, true)}
  );
}
`,
    );
    writeFileSync(
      join(outDir, `${icon.component}.figma.ts`),
      `// url=${figma.fileUrl}?node-id=${icon.nodeId.replace(':', '-')}
// source=${source}
// component=${icon.component}
${HEADER}
import figma from 'figma';

export default {
  example: figma.code\`<${icon.component} />\`,
  imports: ['import { ${icon.component} } from "else-testds"'],
  id: '${icon.component}',
  metadata: { nestable: true },
};
`,
    );
  }

  writeFileSync(
    join(outDir, 'index.ts'),
    `${HEADER}\n${icons.map((i) => `export { ${i.component} } from './${i.component}';`).join('\n')}\n`,
  );

  writeFileSync(
    join(outDir, 'catalog.ts'),
    `${HEADER}
// Every icon with its Figma name, for Storybook. Not exported from the package.
import type { ComponentType } from 'react';
import type { IconProps } from '../IconProps';
${icons.map((i) => `import { ${i.component} } from './${i.component}';`).join('\n')}

export interface IconEntry {
  /** Component name, e.g. "MiniGolfIcon20" */
  component: string;
  Icon: ComponentType<IconProps>;
  /** Full Figma name, e.g. "20px / Mini-golf" */
  figmaName: string;
  /** Size prefix from the Figma name, e.g. "20px" */
  size: string;
  /** Source file in src/icons/svg/ */
  file: string;
}

export const iconCatalog: IconEntry[] = [
${icons
  .sort((a, b) => a.px - b.px || a.figmaName.localeCompare(b.figmaName))
  .map(
    (i) =>
      `  { component: '${i.component}', Icon: ${i.component}, figmaName: '${i.figmaName}', size: '${i.size}', file: '${i.file}' },`,
  )
  .join('\n')}
];
`,
  );

  console.log(`Generated ${icons.length} icon components and Code Connect templates in ${relative(root, outDir)}/`);
  for (const r of report) {
    const done = [
      r.backgroundsRemoved && `removed ${r.backgroundsRemoved} background rect`,
      r.coloursReplaced.size && `colours to currentColor (${[...r.coloursReplaced].map(([c, n]) => `${c} ×${n}`).join(', ')})`,
      r.idsStripped && `stripped ${r.idsStripped} id(s)`,
    ].filter(Boolean);
    console.log(`  ${r.file}: ${done.length ? done.join('; ') : 'already clean'}`);
    for (const warning of r.warnings) console.log(`    warning: ${warning}`);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) build();
